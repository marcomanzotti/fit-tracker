import { z } from "zod";

// A program (scheda) is one JSON document, validated here and stored whole
// (ADR-0003): weeks -> days -> blocks (single, superset, circuit) -> items.
// Each item has a week-1 prescription, an optional progression rule that derives
// the following weeks, and per-week overrides typed by the PT.

export const SET_TYPES = ["warmup", "work", "backoff", "drop", "amrap"] as const;
export const LOAD_MODES = ["kg", "pct1rm", "rpe", "rir", "bw"] as const;
export const BLOCK_TYPES = ["single", "superset", "circuit"] as const;
export const MAX_WEEKS = 52;

export type SetType = (typeof SET_TYPES)[number];
export type LoadMode = (typeof LOAD_MODES)[number];

// Short ids generated by the editor, stable across versions so the history of
// one prescription survives edits.
const localId = z.string().regex(/^[A-Za-z0-9_-]{1,40}$/);

const repsSchema = z
  .object({ min: z.int().min(0).max(100), max: z.int().min(0).max(100) })
  .refine((reps) => reps.max >= reps.min, "max reps below min reps");

// value: kg, % of 1RM, RPE (1-10) or RIR (0-10) depending on mode; none for bw.
const loadSchema = z.object({ mode: z.enum(LOAD_MODES), value: z.number().min(0).max(1000).optional() });

export const setGroupSchema = z.object({
  type: z.enum(SET_TYPES),
  count: z.int().min(1).max(20),
  reps: repsSchema.optional(),
  seconds: z.int().min(1).max(3600).optional(),
  load: loadSchema.optional(),
});

export const prescriptionSchema = z.object({ sets: z.array(setGroupSchema).min(1).max(10) });

export const progressionSchema = z.discriminatedUnion("rule", [
  z.object({ rule: z.literal("none") }),
  // Per week on work sets: +kg (kg loads) or +percentage points (% of 1RM).
  z.object({ rule: z.literal("load"), step: z.number().min(-50).max(50) }),
  // Per week on work sets: + reps on both ends of the range.
  z.object({ rule: z.literal("reps"), step: z.int().min(-5).max(5) }),
]);

export const itemSchema = z.object({
  id: localId,
  exerciseId: z.uuid(),
  notes: z.string().max(500).optional(),
  restSec: z.int().min(0).max(1800).optional(),
  // Eccentric-pause-concentric-pause, e.g. 3-1-X-0 written "31X0".
  tempo: z.string().regex(/^[0-9X]{4}$/i).optional(),
  base: prescriptionSchema,
  progression: progressionSchema.default({ rule: "none" }),
  overrides: z.record(z.string().regex(/^\d{1,2}$/), prescriptionSchema).default({}),
});

export const blockSchema = z
  .object({
    id: localId,
    type: z.enum(BLOCK_TYPES),
    rounds: z.int().min(1).max(20).optional(),
    restAfterSec: z.int().min(0).max(1800).optional(),
    items: z.array(itemSchema).min(1).max(10),
  })
  .refine((block) => block.type !== "single" || block.items.length === 1, "a single block holds one exercise");

export const daySchema = z.object({
  id: localId,
  label: z.string().trim().min(1).max(60),
  // 1 = Monday ... 7 = Sunday; a hint for the client's calendar, not a rule.
  weekday: z.int().min(1).max(7).optional(),
  notes: z.string().max(1000).optional(),
  blocks: z.array(blockSchema).max(30),
});

export const phaseSchema = z.object({
  id: localId,
  name: z.string().trim().min(1).max(60),
  fromWeek: z.int().min(1).max(MAX_WEEKS),
  toWeek: z.int().min(1).max(MAX_WEEKS),
  deload: z.boolean().default(false),
});

export const programDocumentSchema = z
  .object({
    schemaVersion: z.literal(1),
    weeks: z.int().min(1).max(MAX_WEEKS),
    phases: z.array(phaseSchema).max(20).default([]),
    days: z.array(daySchema).max(14),
  })
  .superRefine((doc, ctx) => {
    const issue = (message: string) => ctx.addIssue({ code: "custom", message });
    for (const phase of doc.phases) {
      if (phase.fromWeek > phase.toWeek || phase.toWeek > doc.weeks) issue(`phase "${phase.name}" is outside the program`);
    }
    const ids = new Set<string>();
    for (const item of allItems(doc)) {
      if (ids.has(item.id)) issue(`duplicate item id ${item.id}`);
      ids.add(item.id);
      for (const week of Object.keys(item.overrides)) {
        if (Number(week) < 1 || Number(week) > doc.weeks) issue(`item ${item.id} overrides week ${week}, not in the program`);
      }
    }
  });

export type SetGroup = z.infer<typeof setGroupSchema>;
export type Prescription = z.infer<typeof prescriptionSchema>;
export type Progression = z.infer<typeof progressionSchema>;
export type ProgramItem = z.infer<typeof itemSchema>;
export type ProgramBlock = z.infer<typeof blockSchema>;
export type ProgramDay = z.infer<typeof daySchema>;
export type ProgramPhase = z.infer<typeof phaseSchema>;
export type ProgramDocument = z.infer<typeof programDocumentSchema>;

export function emptyDocument(weeks = 4): ProgramDocument {
  return { schemaVersion: 1, weeks, phases: [], days: [] };
}

export function allItems(doc: Pick<ProgramDocument, "days">): ProgramItem[] {
  return doc.days.flatMap((day) => day.blocks.flatMap((block) => block.items));
}

export function exerciseIdsOf(doc: Pick<ProgramDocument, "days">): string[] {
  return [...new Set(allItems(doc).map((item) => item.exerciseId))];
}
